import assert from 'node:assert/strict';
import { presentationSession, connectPresentation, validMapState } from '../../wwwroot/js/PresentationSync.js';
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const channels = new Set();
const createChannel = name => {
    const channel = { name, onmessage: null,
        postMessage(data) { for (const peer of channels) if (peer !== channel && peer.name === name) peer.onmessage?.({ data: structuredClone(data) }); },
        close() { channels.delete(channel); }
    };
    channels.add(channel); return channel;
};
const session = presentationSession(storage, () => 'admin-session-0001');
assert.equal(presentationSession(storage, () => 'another-session-0002'), session);
const first = { version: 1, x: -12, y: 34, zoom: 25, selected: { x: -10, y: 35, key: '42/0101' } };
const options = { session, storage, createChannel };
const admin = connectPresentation({ ...options, readOnly: false });
admin.publish(first);
let shown, unrelated;
const viewer = connectPresentation({ ...options, readOnly: true, onState: state => shown = state });
assert.deepEqual(shown, first, 'opening a presentation receives the current snapshot');
const secondViewer = connectPresentation({ ...options, readOnly: true, onState: state => {} });
const other = connectPresentation({ ...options, session: 'unrelated-session-0002', readOnly: true, onState: state => unrelated = state });
const next = { ...first, x: 100, zoom: 55, selected: null };
admin.publish(next);
assert.deepEqual(shown, next, 'camera and deselection propagate');
assert.equal(unrelated, undefined, 'other Admin sessions remain independent');
viewer.publish(first);
assert.deepEqual(shown, next, 'presentation cannot publish');
admin.publish({ ...first, zoom: Infinity });
assert.deepEqual(shown, next, 'invalid state ignored');
viewer.close();
admin.publish(first);
assert.deepEqual(shown, next, 'closed presentation unsubscribes');
const reopened = connectPresentation({ ...options, readOnly: true, onState: state => shown = state });
assert.deepEqual(shown, first, 'reopening restores the last snapshot');
const blockedStorage = { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } };
const liveViewer = connectPresentation({ ...options, storage: blockedStorage, readOnly: true, onState: state => shown = state });
assert.deepEqual(shown, first, 'request obtains current state without storage');
const liveAdmin = connectPresentation({ ...options, session: 'no-storage-session-03', storage: blockedStorage, readOnly: false });
liveAdmin.publish(next);
const late = connectPresentation({ ...options, session: 'no-storage-session-03', storage: blockedStorage, readOnly: true, onState: state => shown = state });
assert.deepEqual(shown, next, 'late join works without storage');
assert.equal(validMapState({ ...first, selected: { x: NaN, y: 1 } }), false);
assert.throws(() => connectPresentation({ ...options, session: '' }), /Present map/);
let pointer, otherPointer;
const pointerViewer = connectPresentation({ ...options, readOnly: true, onPointer: point => pointer = point });
const otherPointerViewer = connectPresentation({ ...options, session: 'unrelated-session-0002', readOnly: true, onPointer: point => otherPointer = point });
admin.publishPointer({ x: -10, y: 35 });
assert.deepEqual(pointer, { x: -10, y: 35 }, 'pointer updates without a camera change');
assert.equal(otherPointer, undefined, 'pointer stays within its paired session');
pointerViewer.publishPointer({ x: 999, y: 999 });
assert.deepEqual(pointer, { x: -10, y: 35 }, 'read-only windows cannot publish pointer positions');
admin.publishPointer({ x: Infinity, y: 0 });
assert.deepEqual(pointer, { x: -10, y: 35 }, 'invalid coordinates ignored');
let latePointer;
const pointerLate = connectPresentation({ ...options, readOnly: true, onPointer: point => latePointer = point });
assert.deepEqual(latePointer, pointer, 'late opening receives the live pointer');
assert.equal(JSON.parse(storage.getItem('mtu.presentation.' + session)).pointer, undefined, 'pointer is never persisted in the cached map snapshot');
admin.publishPointer(null);
assert.equal(pointer, null, 'leaving the Admin map hides the pointer');
admin.publishPointer({ x: 5, y: 6 });
admin.close();
assert.equal(pointer, null, 'disposing the Admin map clears its pointer');
for (const connection of [admin, secondViewer, other, reopened, liveViewer, liveAdmin, late, pointerViewer, otherPointerViewer, pointerLate]) connection.close();
assert.equal(channels.size, 0);
console.log('Presentation snapshot, pairing, read-only, late join, storage failure and cleanup checks passed.');
