import assert from 'node:assert/strict';
import { fitView, zoomView, restoreView, snapToken, tokenInitials, drawFallbackToken, Battlemap } from '../../wwwroot/js/Battlemap.js';
assert.deepEqual(fitView(1000, 600, 2000, 1000), { x:0, y:50, scale:.5 });
assert.deepEqual(fitView(600, 1000, 1000, 2000), { x:50, y:0, scale:.5 });
const zoomed = zoomView({x:0,y:50,scale:.5}, 2, {x:500,y:300}, .1, 8);
assert.deepEqual(zoomed, {x:-500,y:-200,scale:1});
assert.deepEqual(zoomView(zoomed,.5,{x:500,y:300},.1,8),{x:0,y:50,scale:.5});
assert.equal(zoomView(zoomed,100,{x:0,y:0},.1,8).scale,8);
assert.equal(zoomView(zoomed,.001,{x:0,y:0},.1,8).scale,.1);
const saved = {...zoomed,width:1000,height:600,imageWidth:2000,imageHeight:1000};
assert.deepEqual(restoreView(saved,1200,800,2000,1000),{x:-400,y:-100,scale:1});
assert.equal(restoreView(saved,1200,800,2001,1000),null);
assert.equal(restoreView({...saved,scale:NaN},1000,600,2000,1000),null);
assert.equal(restoreView({...saved,scale:0},1000,600,2000,1000),null);
const values=new Map();
globalThis.sessionStorage={setItem:(key,value)=>values.set(key,value),getItem:key=>values.get(key)};
const map = new Battlemap({style:{}}, {}, 'campaign.scene.revision.open');
map.width=1000;map.height=600;map.imageWidth=2000;map.imageHeight=1000;

map.fit(); map.zoomIn();
assert.deepEqual(map.view,zoomed);
assert.deepEqual(restoreView(JSON.parse(values.get(map.key)),1000,600,2000,1000),zoomed);
map.host.removeEventListener=()=>{};
await map.dispose();
assert.equal(map.disposed,true);
assert.deepEqual(restoreView(JSON.parse(values.get(map.key)),1000,600,2000,1000),zoomed,'navigating away saves the viewport');
console.log('Battlemap fit, zoom anchoring, bounds, viewport restore, resize and cleanup checks passed.');

