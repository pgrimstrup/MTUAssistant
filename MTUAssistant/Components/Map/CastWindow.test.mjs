const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
const createChannel=name=>{const p={name,postMessage(data){for(const q of ports)if(q!==p&&q.name===name)q.onmessage?.({data});},close(){ports.delete(p);}};ports.add(p);return p;};
const state={scene:{id:1,campaignId:1,revision:1,gridSize:100,gridColour:'#000000',gridOpacity:50,gridlineWidth:2},tokens:[],view:{x:0,y:0,scale:1,width:1000,height:600,imageWidth:2000,imageHeight:2000}};
const opts={storage,createChannel};
const routes=[];
const viewer=watchBattlemap(session,{...opts,navigate:route=>routes.push(route)});
assert.equal(routes.length,0,'an empty cast session stays on Star Map');
const admin=connectBattlemapPresentation({session,...opts,readOnly:false});
admin.publish(state);assert.deepEqual(routes,[true],'opening Battlemap switches an already open Star Map cast');
admin.publish(state);assert.equal(routes.length,1,'camera updates do not repeat navigation');
viewer.close();
const lateRoutes=[];
const late=watchBattlemap(session,{...opts,navigate:route=>lateRoutes.push(route)});
assert.deepEqual(lateRoutes,[true],'a newly opened cast follows an existing Battlemap');late.close();
admin.publish(null);
const closedRoutes=[];
const closed=watchBattlemap(session,{...opts,navigate:route=>closedRoutes.push(route)});
assert.equal(closedRoutes.length,0,'closed Battlemap does not cause a redirect loop');
closed.close();admin.close();
