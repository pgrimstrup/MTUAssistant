const battle=link();attachCastWindow(battle,session,true,{baseURI,open:(...args)=>{calls.push(args);return popup;}});
clicks.get('click')({preventDefault(){}});
assert.equal(calls.length,1,'the existing popup is reused without opening or resizing another window');
assert.equal(popup.location.href,battle.href);assert.equal(focused,1);
assert.equal(new URL(battle.href).pathname,'/app/battlemap-presentation');
assert.equal(new URL(star.href).pathname,'/app/presentation');
let fallbackPrevented=false;
attachCastWindow(link(),"blocked-popup-session-1234",true,{baseURI,open:()=>null});
clicks.get('click')({preventDefault(){fallbackPrevented=true;}});
assert.equal(fallbackPrevented,false,'a blocked popup preserves the normal link fallback');
let navigated;
const location={href:castUrl(session,true,baseURI).href,replace:url=>navigated=url};
switchCastView(session,true,{location,baseURI});assert.equal(navigated,undefined,'current route does not reload');
switchCastView(session,false,{location,baseURI});assert.equal(navigated,star.href,'closing Battlemap returns the same window to Star Map');
assert.throws(()=>castUrl('bad',true,baseURI));
