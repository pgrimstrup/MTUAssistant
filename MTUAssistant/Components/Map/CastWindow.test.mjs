const session='shared-cast-session-1234',baseURI='https://example.test/app/';
const clicks=new Map(),calls=[];
const link=()=>({addEventListener:(name,fn)=>clicks.set(name,fn),removeEventListener:(name,fn)=>{if(clicks.get(name)===fn)clicks.delete(name);}});
const star=link();let prevented=false;
let focused=0;
const popup={opener:{},closed:false,location:{href: ""},focus(){focused++;}};
const detach=attachCastWindow(star,session,false,{baseURI,open:(...args)=>{calls.push(args);return popup;}});
